CREATE TABLE IF NOT EXISTS records (collection VARCHAR(64) NOT NULL, id VARCHAR(128) NOT NULL, payload CLOB NOT NULL, PRIMARY KEY (collection, id));
CREATE TABLE IF NOT EXISTS seed_state (collection VARCHAR(64) PRIMARY KEY);
CREATE TABLE IF NOT EXISTS local_account (id INT PRIMARY KEY, username VARCHAR(100) NOT NULL, password_hash VARCHAR(255) NOT NULL);
CREATE TABLE IF NOT EXISTS trusted_device (username VARCHAR(100) NOT NULL, token_hash VARCHAR(64) PRIMARY KEY, expires_at BIGINT NOT NULL);
